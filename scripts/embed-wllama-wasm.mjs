// Embed @wllama/wllama's compiled single-thread WebAssembly binary into the
// source tree as a Base64 payload — the same pattern scripts/embed-wasm.mjs
// uses for the Rust/WASM core, applied to the vendored inference runtime
// instead of a per-model kernel. Unlike scripts/embed-model.mjs's per-model
// GGUF payloads, this file is the same for every wllama-backed model, so it
// is generated once here rather than duplicated per model catalog entry.
//
// Reads node_modules/@wllama/wllama's published single-thread build (no
// COOP/COEP cross-origin-isolation headers required, unlike its optional
// multi-thread build — see docs/llm-model.md) and writes
// src/wllama-gen/wllama-wasm-payload.ts. The generated file is committed, like
// src/wasm-gen/, so the app builds and tests without re-reading node_modules.
// Re-run this whenever package.json's @wllama/wllama version changes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const wasmPath = join(root, 'node_modules', '@wllama', 'wllama', 'esm', 'wasm', 'wllama.wasm');
const outDir = join(root, 'src', 'wllama-gen');

const wasmBytes = readFileSync(wasmPath);
const base64 = wasmBytes.toString('base64');
const banner = `// @generated by scripts/embed-wllama-wasm.mjs — do not edit.\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'wllama-wasm-payload.ts'),
  banner +
    `// @wllama/wllama's compiled single-thread WebAssembly binary\n` +
    `// (${wasmBytes.length} bytes), embedded as Base64 so the distribution needs no\n` +
    `// separate .wasm asset and no network access. Decoded into a Blob URL at\n` +
    `// runtime — see src/app/llm/wllama-engine.ts.\n` +
    `export const WLLAMA_WASM_BYTE_LENGTH = ${wasmBytes.length};\n` +
    `export const WLLAMA_WASM_BASE64 =\n  '${base64}';\n`,
);

console.warn(`embed-wllama-wasm: embedded ${wasmBytes.length} bytes of WASM (${base64.length} Base64 chars)`);
